#[derive(Clone, Copy)]
struct ImageTransform {
    crop_x: u32,
    crop_y: u32,
    crop_w: u32,
    crop_h: u32,
    target_w: u32,
    target_h: u32,
    offset_x: u32,
    offset_y: u32,
}

impl ImageTransform {
    fn from_bounds(min_x: u32, min_y: u32, max_x: u32, max_y: u32) -> Self {
        let crop_w = max_x - min_x + 1;
        let crop_h = max_y - min_y + 1;
        let fit = f64::min(
            CANVAS_W as f64 / crop_w as f64,
            CANVAS_H as f64 / crop_h as f64,
        );
        let target_w = ((crop_w as f64 * fit).round() as u32).clamp(1, CANVAS_W);
        let target_h = ((crop_h as f64 * fit).round() as u32).clamp(1, CANVAS_H);
        Self {
            crop_x: min_x,
            crop_y: min_y,
            crop_w,
            crop_h,
            target_w,
            target_h,
            offset_x: (CANVAS_W - target_w) / 2,
            offset_y: CANVAS_H - target_h,
        }
    }
}

