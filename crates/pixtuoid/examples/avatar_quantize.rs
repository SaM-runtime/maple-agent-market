fn parse_args() -> Result<(QuantizeMode, PathBuf, Option<PathBuf>, Vec<PathBuf>)> {
    let mut args = env::args_os().skip(1).collect::<Vec<_>>();
    let mode = match args.first().and_then(|arg| arg.to_str()) {
        Some("--walk-cycle") => {
            args.remove(0);
            QuantizeMode::WalkCycle
        }
        Some("--market-cycle") => {
            args.remove(0);
            QuantizeMode::MarketCycle
        }
        Some("--status-cycle") => {
            args.remove(0);
            QuantizeMode::StatusCycle
        }
        Some("--combat-cycle") => {
            args.remove(0);
            QuantizeMode::CombatCycle
        }
        Some("--skill-effect") => {
            args.remove(0);
            QuantizeMode::SkillEffect
        }
        _ => QuantizeMode::Static,
    };
    let output_dir = PathBuf::from(args.first().cloned().context(
        "usage: avatar_quantize [--walk-cycle|--market-cycle|--status-cycle] <output-dir> <avatar images...> | [--combat-cycle|--skill-effect] <output-dir> <pack.toml> <images...>",
    )?);
    args.remove(0);
    let palette_path = if matches!(mode, QuantizeMode::CombatCycle | QuantizeMode::SkillEffect) {
        let path =
            PathBuf::from(args.first().cloned().context(
                "--combat-cycle and --skill-effect need the existing pack.toml after the output directory",
            )?);
        args.remove(0);
        Some(path)
    } else {
        None
    };
    let inputs = args.into_iter().map(PathBuf::from).collect::<Vec<_>>();
    let expected = mode.expected_inputs();
    if inputs.len() != expected {
        bail!(
            "usage: avatar_quantize [--walk-cycle|--market-cycle|--status-cycle] <output-dir> <avatar images...> | [--combat-cycle|--skill-effect] <output-dir> <pack.toml> <images...> (need {expected}, got {})",
            inputs.len()
        );
    }
    Ok((mode, output_dir, palette_path, inputs))
}

fn load_sources(inputs: &[PathBuf]) -> Result<Vec<RgbaImage>> {
    inputs
        .iter()
        .map(|path| {
            Ok(image::open(path)
                .with_context(|| format!("decoding {}", path.display()))?
                .to_rgba8())
        })
        .collect()
}

fn normalize_inputs(
    mode: QuantizeMode,
    inputs: &[PathBuf],
    sources: &[RgbaImage],
) -> Result<Vec<RgbaImage>> {
    match mode {
        QuantizeMode::Static => sources
            .iter()
            .zip(inputs)
            .map(|(source, path)| {
                normalize_avatar(source).with_context(|| format!("normalizing {}", path.display()))
            })
            .collect(),
        QuantizeMode::WalkCycle => {
            let mut normalized = Vec::with_capacity(sources.len());
            for sequence in sources.chunks_exact(WALK_SEQUENCE_FRAMES) {
                normalized.extend(normalize_avatar_sequence(sequence)?);
            }
            Ok(normalized)
        }
        QuantizeMode::MarketCycle => {
            let mut normalized = Vec::with_capacity(sources.len());
            for sequence in sources.chunks_exact(MARKET_SEQUENCE_FRAMES) {
                normalized.extend(normalize_avatar_sequence(sequence)?);
            }
            Ok(normalized)
        }
        QuantizeMode::StatusCycle => {
            let mut normalized = Vec::with_capacity(sources.len());
            for sequence in sources.chunks_exact(STATUS_SEQUENCE_FRAMES) {
                normalized.extend(normalize_avatar_sequence(sequence)?);
            }
            Ok(normalized)
        }
        QuantizeMode::CombatCycle => {
            let mut normalized = Vec::with_capacity(sources.len());
            for sequence in sources.chunks_exact(COMBAT_SEQUENCE_FRAMES) {
                normalized.extend(normalize_combat_sequence(sequence)?);
            }
            Ok(normalized)
        }
        QuantizeMode::SkillEffect => normalize_magic_claw_frames(sources),
    }
}

fn normalize_magic_claw_frames(sources: &[RgbaImage]) -> Result<Vec<RgbaImage>> {
    if sources.len() != MAGIC_CLAW_FRAME_SIZES.len() {
        bail!(
            "Magic Claw needs {} frames, got {}",
            MAGIC_CLAW_FRAME_SIZES.len(),
            sources.len()
        );
    }

    sources
        .iter()
        .zip(MAGIC_CLAW_FRAME_SIZES)
        .zip(MAGIC_CLAW_ORIGINS)
        .enumerate()
        .map(|(index, ((source, expected_size), (origin_x, origin_y)))| {
            if source.dimensions() != expected_size {
                bail!(
                    "Magic Claw frame {index} expected {}x{}, got {}x{}",
                    expected_size.0,
                    expected_size.1,
                    source.width(),
                    source.height()
                );
            }
            let x = MAGIC_CLAW_CANVAS_ORIGIN_X
                .checked_sub(origin_x)
                .context("Magic Claw x origin does not fit the shared canvas")?;
            let y = MAGIC_CLAW_CANVAS_ORIGIN_Y
                .checked_sub(origin_y)
                .context("Magic Claw y origin does not fit the shared canvas")?;
            if x + source.width() > MAGIC_CLAW_CANVAS_W || y + source.height() > MAGIC_CLAW_CANVAS_H
            {
                bail!("Magic Claw frame {index} exceeds the shared canvas");
            }
            let mut canvas =
                RgbaImage::from_pixel(MAGIC_CLAW_CANVAS_W, MAGIC_CLAW_CANVAS_H, Rgba([0, 0, 0, 0]));
            image::imageops::overlay(&mut canvas, source, i64::from(x), i64::from(y));
            Ok(canvas)
        })
        .collect()
}

fn main() -> Result<()> {
    let (mode, output_dir, palette_path, inputs) = parse_args()?;
    let sources = load_sources(&inputs)?;
    let images = normalize_inputs(mode, &inputs, &sources)?;
    match mode {
        QuantizeMode::Static => write_outputs(&output_dir, &inputs, &images)?,
        QuantizeMode::WalkCycle => write_walk_outputs(&output_dir, &inputs, &images)?,
        QuantizeMode::MarketCycle => write_market_outputs(&output_dir, &inputs, &images)?,
        QuantizeMode::StatusCycle => write_status_outputs(&output_dir, &inputs, &images)?,
        QuantizeMode::CombatCycle => write_combat_outputs(
            &output_dir,
            palette_path
                .as_deref()
                .expect("combat parsing requires an existing palette"),
            &inputs,
            &images,
        )?,
        QuantizeMode::SkillEffect => write_skill_effect_outputs(
            &output_dir,
            palette_path
                .as_deref()
                .expect("skill-effect parsing requires an existing palette"),
            &inputs,
            &images,
        )?,
    }
    println!("inputs={}", inputs.len());
    let (canvas_w, canvas_h) = match mode {
        QuantizeMode::CombatCycle => (COMBAT_CANVAS_W, COMBAT_CANVAS_H),
        QuantizeMode::SkillEffect => (MAGIC_CLAW_CANVAS_W, MAGIC_CLAW_CANVAS_H),
        _ => (CANVAS_W, CANVAS_H),
    };
    println!("canvas={canvas_w}x{canvas_h}");
    println!("output={}", output_dir.display());
    Ok(())
}

